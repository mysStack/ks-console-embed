#!/usr/bin/env python3
from pathlib import Path
import re

UNPACKED = Path("/home/bruce/code/ks-develop/kse-console-v3/recovery/react-app/src/unpacked")
STUB_RE = re.compile(
    r'^export \{ default \} from "(pages|components|stores|actions|utils|configs|core|dmp)/'
)
NEEDLES = (
    "stores/devops/imageBuilderRun",
    "hiddenLog",
    "imageBuilderName",
    "LAST_BUILD_ENVIRONMENT",
    "RUN_RECORDS",
    "isBinaryURL",
    "sort_type",
    "stores/rank/node",
    "stores/rank/project",
    "stores/rank/workspace",
)
for p in UNPACKED.glob("module-*.js"):
    text = p.read_text(encoding="utf-8", errors="ignore")
    if STUB_RE.match(text) or text.startswith('export { default } from "chunks/'):
        continue
    hits = [n for n in NEEDLES if n in text]
    if hits:
        print(p.name, hits)
